// Package vectors builds the conformance vectors in edgeauth/testdata
// (vectors.json): a JWKS, a fixed "now", and tokens with the result every
// verifier must give for them. The Go verifier, the TypeScript verifier and
// guard's signer test all run them.
//
// The tokens are assembled by hand, not with a JOSE library, so a vector
// can break the rules in ways a library refuses to (alg none, a DER
// signature) and so the verifiers are checked against an independent
// encoder. ECDSA signatures are deterministic (RFC 6979), so the output is
// stable and the edgeauth tests check the committed file is current.
package vectors

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/hmac"
	"crypto/sha256"
	"crypto/x509"
	"encoding/asn1"
	"encoding/base64"
	"encoding/json"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"strings"
)

// The fixed key and clock of the vectors.
const (
	// KeyID is the kid of the vectors' only published key.
	KeyID = "vectors-2026-11-a"
	// Now is the time the verifiers run the vectors at (2027-01-01T00:00:00Z).
	Now = 1798761600
	// Audience is the host most vectors are minted for.
	Audience = "live.metsa.app"
)

// signingKeyPEM is the published key. It is a test key: it signs nothing but
// these vectors.
const signingKeyPEM = `-----BEGIN PRIVATE KEY-----
MIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQgGaBAURWXeaTW2jDS
gGE88+H0gB04n8Rg37ajnoxgvkyhRANCAARMUjHkSfTB0fCnaCfikau/ijQQEnNZ
0NdQrHvNNdhGr917ST60SWXseBRMJiDkMLS9G4lb3XrEa+TThIHr+HJw
-----END PRIVATE KEY-----
`

// otherKeyPEM is not published; tokens it signs under KeyID are forgeries.
const otherKeyPEM = `-----BEGIN PRIVATE KEY-----
MIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQgB0721h7M82AYVhC+
Z3vvougCyipORzP5pCSyiMUL39GhRANCAAS+u20iv5NcuK6DAt33DWCZltOyoeSv
FmfFrFnJes45k0+xV3VPfjGSgn1E/WbcQFD99YstnA4XsmHzWoOrds0E
-----END PRIVATE KEY-----
`

// coordinateBytes is the length of a P-256 coordinate and of each half of an
// ES256 signature.
const coordinateBytes = 32

// File is vectors.json.
type File struct {
	Comment string `json:"comment"`
	Now     int64  `json:"now"`
	JWKS    JWKS   `json:"jwks"`
	Cases   []Case `json:"cases"`
}

// JWKS is the published key set.
type JWKS struct {
	Keys []JWK `json:"keys"`
}

// JWK is one published key.
type JWK struct {
	Kty string `json:"kty"`
	Crv string `json:"crv"`
	X   string `json:"x"`
	Y   string `json:"y"`
	Kid string `json:"kid"`
	Use string `json:"use"`
	Alg string `json:"alg"`
}

// Case is one token and what a verifier must make of it.
type Case struct {
	Name      string   `json:"name"`
	Token     string   `json:"token"`
	Audiences []string `json:"audiences"`
	// JWKSUnreachable runs the case with guard's JWKS endpoint down.
	JWKSUnreachable bool `json:"jwksUnreachable,omitempty"`
	Want            Want `json:"want"`
}

// Want is either an identity (OK) or an error class, "invalid" or
// "unavailable".
type Want struct {
	OK            bool     `json:"ok"`
	Error         string   `json:"error,omitempty"`
	Subject       string   `json:"subject,omitempty"`
	Email         string   `json:"email,omitempty"`
	EmailVerified bool     `json:"emailVerified,omitempty"`
	Name          string   `json:"name,omitempty"`
	Roles         []string `json:"roles,omitempty"`
	SessionID     string   `json:"sessionId,omitempty"`
	AuthTime      int64    `json:"authTime,omitempty"`
	ClientID      string   `json:"clientId,omitempty"`
	Source        string   `json:"source,omitempty"`
}

// Error classes of Want.
const (
	Invalid     = "invalid"
	Unavailable = "unavailable"
)

type claims = map[string]any

type header = map[string]any

// generator holds the keys while the cases are built.
type generator struct {
	key, other *ecdsa.PrivateKey
}

// Generate returns vectors.json.
func Generate() ([]byte, error) {
	key, err := parseKey(signingKeyPEM)
	if err != nil {
		return nil, err
	}
	other, err := parseKey(otherKeyPEM)
	if err != nil {
		return nil, err
	}
	g := generator{key: key, other: other}
	cases, err := g.cases()
	if err != nil {
		return nil, err
	}
	jwk, err := publicJWK(&key.PublicKey)
	if err != nil {
		return nil, err
	}
	file := File{
		Comment: "Generated by edgeauth/internal/vectorgen (go generate ./edgeauth). " +
			"Run each case at now (unix seconds) against jwks; the key is a test key.",
		Now:   Now,
		JWKS:  JWKS{Keys: []JWK{jwk}},
		Cases: cases,
	}
	out, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal vectors: %w", err)
	}
	return append(out, '\n'), nil
}

// base is a valid session token's claims.
//
//nolint:mnd // times are offsets from Now
func base() claims {
	return claims{
		"iss":            "bastion",
		"aud":            Audience,
		"sub":            "302871234567890123",
		"email":          "ada@example.org",
		"email_verified": true,
		"name":           "Ada Lovelace",
		"roles":          []string{"admin", "member"},
		"sid":            "0123456789abcdef",
		"auth_time":      Now - 3600,
		"azp":            "294729172937281",
		"src":            "session",
		"iat":            Now - 5,
		"exp":            Now + 55,
	}
}

//nolint:mnd // times are offsets from Now
func baseWant() Want {
	return Want{
		OK:            true,
		Subject:       "302871234567890123",
		Email:         "ada@example.org",
		EmailVerified: true,
		Name:          "Ada Lovelace",
		Roles:         []string{"admin", "member"},
		SessionID:     "0123456789abcdef",
		AuthTime:      Now - 3600,
		ClientID:      "294729172937281",
		Source:        "session",
	}
}

func esHeader() header {
	return header{"alg": "ES256", "typ": "bastion-id+jwt", "kid": KeyID}
}

func with(c claims, edit func(claims)) claims {
	edit(c)
	return c
}

func withHeader(edit func(header)) header {
	h := esHeader()
	edit(h)
	return h
}

func invalid() Want { return Want{Error: Invalid} }

//nolint:funlen,mnd // one table of cases, with times as offsets from Now
func (g generator) cases() ([]Case, error) {
	one := []string{Audience}
	type spec struct {
		name      string
		header    header
		claims    claims
		sign      func(signingInput string) (string, error)
		audiences []string
		down      bool
		want      Want
	}
	es := g.es256(g.key)
	specs := []spec{
		{name: "valid session", claims: base(), want: baseWant()},
		{
			name: "valid bearer",
			claims: with(base(), func(c claims) {
				c["src"], c["sid"], c["azp"], c["roles"] = "bearer", "", "394513759751636980", []string{"member"}
			}),
			want: func() Want {
				w := baseWant()
				w.Source, w.SessionID, w.ClientID, w.Roles = "bearer", "", "394513759751636980", []string{"member"}
				return w
			}(),
		},
		{
			name:   "roles empty",
			claims: with(base(), func(c claims) { c["roles"] = []string{} }),
			want:   func() Want { w := baseWant(); w.Roles = nil; return w }(),
		},
		{
			name:   "roles absent",
			claims: with(base(), func(c claims) { delete(c, "roles") }),
			want:   func() Want { w := baseWant(); w.Roles = nil; return w }(),
		},
		{
			name: "empty profile",
			claims: with(base(), func(c claims) {
				c["email"], c["email_verified"], c["name"] = "", false, ""
				delete(c, "auth_time")
			}),
			want: func() Want {
				w := baseWant()
				w.Email, w.EmailVerified, w.Name, w.AuthTime = "", false, "", 0
				return w
			}(),
		},
		{
			name:      "second audience",
			claims:    with(base(), func(c claims) { c["aud"] = "admin.live.metsa.app" }),
			audiences: []string{Audience, "admin.live.metsa.app"},
			want:      baseWant(),
		},
		{
			name:   "aud array containing the audience",
			claims: with(base(), func(c claims) { c["aud"] = []string{"other.metsa.app", Audience} }),
			want:   baseWant(),
		},
		{
			name:   "typ with application prefix",
			header: withHeader(func(h header) { h["typ"] = "application/bastion-id+jwt" }),
			claims: base(), want: baseWant(),
		},
		{
			name:   "expired within leeway",
			claims: with(base(), func(c claims) { c["iat"], c["exp"] = Now-69, Now-9 }),
			want:   baseWant(),
		},
		{
			name:   "expired",
			claims: with(base(), func(c claims) { c["iat"], c["exp"] = Now-70, Now-10 }),
			want:   invalid(),
		},
		{
			name:   "iat ahead within leeway",
			claims: with(base(), func(c claims) { c["iat"], c["exp"] = Now+10, Now+70 }),
			want:   baseWant(),
		},
		{
			name:   "future iat",
			claims: with(base(), func(c claims) { c["iat"], c["exp"] = Now+11, Now+71 }),
			want:   invalid(),
		},
		{
			name:   "future nbf",
			claims: with(base(), func(c claims) { c["nbf"] = Now + 30 }),
			want:   invalid(),
		},
		{name: "wrong aud", claims: with(base(), func(c claims) { c["aud"] = "other.metsa.app" }), want: invalid()},
		{
			name:   "aud not lower case",
			claims: with(base(), func(c claims) { c["aud"] = "Live.Metsa.App" }),
			want:   invalid(),
		},
		{
			name:   "wrong iss",
			claims: with(base(), func(c claims) { c["iss"] = "https://auth.metsa.app" }),
			want:   invalid(),
		},
		{name: "missing sub", claims: with(base(), func(c claims) { delete(c, "sub") }), want: invalid()},
		{name: "missing exp", claims: with(base(), func(c claims) { delete(c, "exp") }), want: invalid()},
		{name: "missing iat", claims: with(base(), func(c claims) { delete(c, "iat") }), want: invalid()},
		{
			name:   "email_verified not a bool",
			claims: with(base(), func(c claims) { c["email_verified"] = "true" }),
			want:   invalid(),
		},
		{name: "roles not a list", claims: with(base(), func(c claims) { c["roles"] = "admin" }), want: invalid()},
		{
			name:   "alg HS256 keyed with the public key",
			header: withHeader(func(h header) { h["alg"] = "HS256" }),
			claims: base(), sign: g.hs256(), want: invalid(),
		},
		{
			name:   "alg none",
			header: withHeader(func(h header) { h["alg"] = "none" }),
			claims: base(), sign: func(string) (string, error) { return "", nil }, want: invalid(),
		},
		{
			name:   "wrong typ",
			header: withHeader(func(h header) { h["typ"] = "JWT" }),
			claims: base(), want: invalid(),
		},
		{name: "missing typ", header: withHeader(func(h header) { delete(h, "typ") }), claims: base(), want: invalid()},
		{
			name:   "unknown kid",
			header: withHeader(func(h header) { h["kid"] = "vectors-unknown" }),
			claims: base(), want: invalid(),
		},
		{name: "missing kid", header: withHeader(func(h header) { delete(h, "kid") }), claims: base(), want: invalid()},
		{name: "bad signature", claims: base(), sign: g.es256(g.other), want: invalid()},
		{name: "DER signature", claims: base(), sign: g.es256DER(), want: invalid()},
		{name: "valid token, JWKS unreachable", claims: base(), down: true, want: Want{Error: Unavailable}},
	}
	cases := make([]Case, 0, len(specs)+2)
	for _, s := range specs {
		h, sign, aud := s.header, s.sign, s.audiences
		if h == nil {
			h = esHeader()
		}
		if sign == nil {
			sign = es
		}
		if aud == nil {
			aud = one
		}
		token, err := assemble(h, s.claims, sign)
		if err != nil {
			return nil, fmt.Errorf("case %q: %w", s.name, err)
		}
		cases = append(cases, Case{Name: s.name, Token: token, Audiences: aud, JWKSUnreachable: s.down, Want: s.want})
	}
	tampered, err := g.tampered()
	if err != nil {
		return nil, err
	}
	cases = append(cases,
		Case{Name: "payload changed after signing", Token: tampered, Audiences: one, Want: invalid()},
		Case{Name: "not a JWS", Token: "not-a-token", Audiences: one, Want: invalid()},
	)
	return cases, nil
}

// tampered is a valid token whose payload is swapped for one granting more
// roles, keeping the original signature.
func (g generator) tampered() (string, error) {
	token, err := assemble(esHeader(), base(), g.es256(g.key))
	if err != nil {
		return "", err
	}
	elevated := with(base(), func(c claims) { c["roles"] = []string{"admin", "cluster-admin", "member"} })
	payload, err := json.Marshal(elevated)
	if err != nil {
		return "", fmt.Errorf("marshal claims: %w", err)
	}
	parts := strings.Split(token, ".")
	return parts[0] + "." + b64(payload) + "." + parts[2], nil
}

func assemble(h header, c claims, sign func(string) (string, error)) (string, error) {
	hb, err := json.Marshal(h)
	if err != nil {
		return "", fmt.Errorf("marshal header: %w", err)
	}
	cb, err := json.Marshal(c)
	if err != nil {
		return "", fmt.Errorf("marshal claims: %w", err)
	}
	input := b64(hb) + "." + b64(cb)
	sig, err := sign(input)
	if err != nil {
		return "", err
	}
	return input + "." + sig, nil
}

// es256 signs with key, deterministically, as r || s.
func (g generator) es256(key *ecdsa.PrivateKey) func(string) (string, error) {
	return func(input string) (string, error) {
		r, s, err := signRS(key, input)
		if err != nil {
			return "", err
		}
		sig := make([]byte, coordinateBytes+coordinateBytes)
		r.FillBytes(sig[:coordinateBytes])
		s.FillBytes(sig[coordinateBytes:])
		return b64(sig), nil
	}
}

// es256DER signs with the published key but encodes the signature as ASN.1
// DER, which JWS does not allow.
func (g generator) es256DER() func(string) (string, error) {
	return func(input string) (string, error) {
		r, s, err := signRS(g.key, input)
		if err != nil {
			return "", err
		}
		der, err := asn1.Marshal(struct{ R, S *big.Int }{r, s})
		if err != nil {
			return "", fmt.Errorf("marshal DER signature: %w", err)
		}
		return b64(der), nil
	}
}

// hs256 is the classic key-confusion forgery: an HMAC keyed with the
// published public key's encoding.
func (g generator) hs256() func(string) (string, error) {
	return func(input string) (string, error) {
		pub, err := x509.MarshalPKIXPublicKey(&g.key.PublicKey)
		if err != nil {
			return "", fmt.Errorf("marshal public key: %w", err)
		}
		mac := hmac.New(sha256.New, pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: pub}))
		mac.Write([]byte(input))
		return b64(mac.Sum(nil)), nil
	}
}

func signRS(key *ecdsa.PrivateKey, input string) (*big.Int, *big.Int, error) {
	digest := sha256.Sum256([]byte(input))
	// A nil random source signs deterministically (RFC 6979).
	der, err := key.Sign(nil, digest[:], crypto.SHA256)
	if err != nil {
		return nil, nil, fmt.Errorf("sign: %w", err)
	}
	var sig struct{ R, S *big.Int }
	if _, err = asn1.Unmarshal(der, &sig); err != nil {
		return nil, nil, fmt.Errorf("parse signature: %w", err)
	}
	return sig.R, sig.S, nil
}

func publicJWK(pub *ecdsa.PublicKey) (JWK, error) {
	// Bytes is the uncompressed point: 0x04 || x || y.
	point, err := pub.Bytes()
	if err != nil {
		return JWK{}, fmt.Errorf("encode public key: %w", err)
	}
	return JWK{
		Kty: "EC", Crv: "P-256",
		X:   b64(point[1 : 1+coordinateBytes]),
		Y:   b64(point[1+coordinateBytes:]),
		Kid: KeyID, Use: "sig", Alg: "ES256",
	}, nil
}

func parseKey(text string) (*ecdsa.PrivateKey, error) {
	block, _ := pem.Decode([]byte(text))
	if block == nil {
		return nil, errors.New("vectors: no PEM block")
	}
	key, err := x509.ParsePKCS8PrivateKey(block.Bytes)
	if err != nil {
		return nil, fmt.Errorf("parse key: %w", err)
	}
	ec, ok := key.(*ecdsa.PrivateKey)
	if !ok {
		return nil, errors.New("vectors: key is not ECDSA")
	}
	return ec, nil
}

func b64(b []byte) string {
	return base64.RawURLEncoding.EncodeToString(b)
}
